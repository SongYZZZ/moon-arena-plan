"""Independent black-box layout checks; not part of the planning implementation."""
import argparse, json, random, subprocess, tempfile, sys
from pathlib import Path

def check(problem, layout):
    banks={x['id']:int(x['capacity']) for x in problem['banks']}
    buffers={x['id']:x for x in problem['buffers']}
    placements=layout['placements']
    assert len(placements)==len(buffers)
    assert {x['id'] for x in placements}==set(buffers)
    for x in placements:
        b=buffers[x['id']];off=int(x['offset']);end=off+int(b['bytes'])
        assert x['bank'] in b['banks'] and 0<=off<end<=banks[x['bank']]
        assert off%int(b['alignment'])==0
        if b.get('fixed_bank') is not None:assert (x['bank'],off)==(b['fixed_bank'],int(b['fixed_offset']))
    for i,x in enumerate(placements):
        a=buffers[x['id']]
        for y in placements[i+1:]:
            b=buffers[y['id']]
            if x['bank']!=y['bank'] or a['last']<b['first'] or b['last']<a['first']:continue
            assert int(x['offset'])+int(a['bytes'])<=int(y['offset']) or int(y['offset'])+int(b['bytes'])<=int(x['offset'])
    return banks,buffers

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--exe',required=True);ap.add_argument('--cases',type=int,default=200)
    ns=ap.parse_args();exe=str(Path(ns.exe).resolve());root=Path(__file__).resolve().parents[1]
    records=[]
    def run(args,expected=0):
        p=subprocess.run([exe,*map(str,args)],capture_output=True,text=True,encoding='utf8',timeout=20)
        assert p.returncode==expected,(args,p.returncode,p.stdout,p.stderr)
        return json.loads(p.stdout) if p.stdout.lstrip().startswith('{') else p.stdout
    tempbase=Path('D:/Dev/Temp') if Path('D:/Dev/Temp').is_dir() else root/'.tools/temporary'
    tempbase.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='arena-verify-',dir=tempbase) as temporary:
        work=Path(temporary);assert work.resolve().is_relative_to(tempbase.resolve())
        case=work/'case.json';layoutfile=work/'layout.json'
        for name in ['reuse','dma_banks']:
            p=json.loads((root/'examples'/f'{name}.json').read_text());report=run(['plan',root/'examples'/f'{name}.json']);check(p,report['layout'])
            records.append({'case':name,'banks':report['banks']})
        bad=run(['plan',root/'examples/budget_failure.json'],1)
        assert any(f['code']=='CapacityExceeded' for f in bad['findings'])
        for seed in range(ns.cases):
            rng=random.Random(seed);p={'schema':1,'banks':[{'id':'fast','capacity':'8192'},{'id':'dma','capacity':'8192'}],'buffers':[]}
            for i in range(16):
                first=rng.randrange(20);p['buffers'].append({'id':f'b{i}','bytes':str(rng.randrange(1,65)),'first':first,'last':first+rng.randrange(5),'alignment':str(1<<rng.randrange(6)),'banks':rng.choice([['fast'],['dma'],['dma','fast']])})
            case.write_text(json.dumps(p));report=run(['plan',case]);layout=report['layout'];check(p,layout)
            for bank in report['banks']:
                bankid=bank['bank'];byid={b['id']:b for b in p['buffers']};members=[q for q in layout['placements'] if q['bank']==bankid]
                high=max([int(q['offset'])+int(byid[q['id']]['bytes']) for q in members],default=0)
                peak=max([sum(int(byid[q['id']]['bytes']) for q in members if byid[q['id']]['first']<=t<=byid[q['id']]['last']) for t in range(25)])
                assert (high,peak)==(int(bank['highwater']),int(bank['peak_live_bytes']))
            rng.shuffle(p['buffers']);case.write_text(json.dumps(p));assert run(['layout',case])==layout
        # Negative JSON and forged layout paths.
        case.write_text('{"schema":1.5,"banks":[],"buffers":[]}');run(['plan',case],2)
        case.write_text('{"schema":1,"banks":[],"buffers":[],"typo":1}');run(['plan',case],2)
        case.write_text('{"schema":1,"schema":1}');run(['plan',case],2)
        p=json.loads((root/'examples/reuse.json').read_text());case.write_text(json.dumps(p))
        layout=run(['layout',case]);layout['placements'][0]['offset']='-1';layoutfile.write_text(json.dumps(layout))
        forged=run(['verify',case,layoutfile],1);assert any(f['code']=='AddressRange' for f in forged['findings'])
        run(['header',case,layoutfile],2)
        # Compile target header is generated by the real executable, not hand authored.
        replay=root/'examples/c_replay.json';l=run(['layout',replay]);layoutfile.write_text(json.dumps(l))
        header=run(['header',replay,layoutfile]);(root/'examples/c_replay/generated_plan.h').write_text(header,encoding='utf8')
    out={'random_schedules':ns.cases,'reordered_schedules':ns.cases,'negative_cli_cases':5,'scenarios':records,'status':'passed'}
    artifacts=root/'artifacts';artifacts.mkdir(exist_ok=True);(artifacts/'verification.json').write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps(out,indent=2))
if __name__=='__main__':main()
